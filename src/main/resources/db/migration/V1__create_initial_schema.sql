CREATE TABLE roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE business_stores (
    business_store_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_store_name VARCHAR(160) NOT NULL,
    registry_number VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active',
    role_id BIGINT NOT NULL,
    business_store_id BIGINT,
    created_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id) REFERENCES roles (role_id),
    CONSTRAINT fk_users_business_store
        FOREIGN KEY (business_store_id) REFERENCES business_stores (business_store_id)
        ON DELETE SET NULL
);

CREATE TABLE vouchers (
    voucher_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value NUMERIC(18, 2) NOT NULL CHECK (value > 0),
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
    used_date TIMESTAMPTZ,
    expiry_date TIMESTAMPTZ NOT NULL,
    added_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    voucher_code VARCHAR(128) NOT NULL,
    user_id BIGINT NOT NULL,
    business_store_id BIGINT NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    CONSTRAINT uk_vouchers_code UNIQUE (voucher_code),
    CONSTRAINT ck_vouchers_source CHECK (source IN ('MANUAL', 'OCR')),
    CONSTRAINT fk_vouchers_user
        FOREIGN KEY (user_id) REFERENCES users (user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_vouchers_business_store
        FOREIGN KEY (business_store_id) REFERENCES business_stores (business_store_id)
        ON DELETE RESTRICT
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(64) NOT NULL,
    target_user_id BIGINT,
    admin_user_id BIGINT,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details TEXT,
    CONSTRAINT fk_audit_target_user
        FOREIGN KEY (target_user_id) REFERENCES users (user_id)
        ON DELETE SET NULL,
    CONSTRAINT fk_audit_admin_user
        FOREIGN KEY (admin_user_id) REFERENCES users (user_id)
        ON DELETE SET NULL
);

CREATE INDEX idx_users_role_id ON users (role_id);
CREATE INDEX idx_users_business_store_id ON users (business_store_id);
CREATE INDEX idx_vouchers_user_id ON vouchers (user_id);
CREATE INDEX idx_vouchers_business_store_id ON vouchers (business_store_id);
CREATE INDEX idx_vouchers_expiry_date ON vouchers (expiry_date);
CREATE INDEX idx_vouchers_used_date ON vouchers (used_date);
CREATE INDEX idx_audit_logs_timestamp ON audit_logs (timestamp);

